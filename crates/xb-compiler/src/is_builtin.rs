//! Canonical set of XBasic builtin function names.
//!
//! Single source of truth shared by the interpreter (`xb-runtime`, which depends
//! on this crate) and the LLVM backend. The backend uses it to tell a *deferred*
//! builtin (one the interpreter implements but LLVM does not yet) apart from an
//! *unknown* user function: the former must be skipped, the latter is stubbed to
//! the zero-default exactly as the interpreter's `call_function` stub does.
